import 'dart:convert';

/// One item of a flat playlist (`CommandBuilder.playlist`): enough to list
/// it and to download it later, nothing read from its own page.
class PlaylistEntry {
  const PlaylistEntry({
    required this.id,
    required this.url,
    this.title,
    this.duration,
  });

  final String id;
  final String url;
  final String? title;
  final Duration? duration;
}

/// What yt-dlp read about a link: a probe's `-J` output, or the
/// `.info.json` written beside a finished file.
///
/// Only the fields the apps use are read, and each tolerantly: a site
/// leaves out what it does not have, and a field of the wrong type reads
/// as missing rather than failing the whole reading.
class InfoJson {
  InfoJson._(this.raw);

  /// Reads [text]; throws [FormatException] when it is not a JSON object.
  factory InfoJson.parse(String text) {
    final Object? decoded = jsonDecode(text);
    if (decoded is! Map<String, Object?>) {
      throw const FormatException('the info JSON is not an object');
    }
    return InfoJson._(decoded);
  }

  /// Everything yt-dlp wrote, for what this class does not name.
  final Map<String, Object?> raw;

  String? _text(String key) => switch (raw[key]) {
    final String s when s.isNotEmpty => s,
    _ => null,
  };

  int? _int(String key) => switch (raw[key]) {
    final num n => n.round(),
    _ => null,
  };

  bool get isPlaylist => raw['_type'] == 'playlist';

  String? get id => _text('id');
  String? get title => _text('title');

  /// The person or channel behind it, under whichever name the site uses.
  String? get uploader =>
      _text('uploader') ?? _text('channel') ?? _text('creator');

  /// The page the link resolves to, the stable form of what was pasted.
  String? get webpageUrl => _text('webpage_url') ?? _text('original_url');

  /// yt-dlp's name for the site, such as `Youtube` or `Instagram`.
  String? get extractor => _text('extractor_key') ?? _text('extractor');

  String? get thumbnail => _text('thumbnail');

  Duration? get duration => switch (raw['duration']) {
    final num s => Duration(milliseconds: (s * 1000).round()),
    _ => null,
  };

  /// When it was published, from the exact time or else the day.
  DateTime? get published {
    if (_int('timestamp') case final t?) {
      return DateTime.fromMillisecondsSinceEpoch(t * 1000, isUtc: true);
    }
    final day = _text('upload_date');
    if (day == null || day.length != 8) return null;
    return DateTime.tryParse(
      '${day.substring(0, 4)}-${day.substring(4, 6)}-${day.substring(6)}',
    );
  }

  /// `is_live`, `is_upcoming` and the like: such a link has no file yet,
  /// or no end.
  bool get isLive => switch (_text('live_status')) {
    'is_live' || 'is_upcoming' => true,
    _ => raw['is_live'] == true,
  };

  /// The size of what yt-dlp would pick by default, exact or estimated.
  int? get size => _int('filesize') ?? _int('filesize_approx');

  List<Map<String, Object?>> get _formats => [
    if (raw['formats'] case final List list)
      for (final f in list)
        if (f is Map<String, Object?>) f,
  ];

  static bool _hasVideo(Map<String, Object?> f) =>
      f['vcodec'] is String && f['vcodec'] != 'none';

  /// The picture heights offered, highest first: what the quality list
  /// shows. Empty for a site that does not say, or for sound alone.
  List<int> get heights {
    final found = <int>{
      for (final f in _formats)
        if (_hasVideo(f) && f['height'] is num) (f['height'] as num).round(),
    };
    return found.toList()..sort((a, b) => b.compareTo(a));
  }

  /// Whether any format carries a picture; false for a song or a podcast.
  bool get hasVideo => _formats.isEmpty
      ? _text('vcodec') != null && _text('vcodec') != 'none'
      : _formats.any(_hasVideo);

  /// Whether an H.264 picture exists at [maxHeight] or below, so the
  /// compatible download keeps the quality asked for.
  bool offersH264({int? maxHeight}) => _formats.any((f) {
    final codec = f['vcodec'];
    final h = f['height'];
    return codec is String &&
        (codec.startsWith('avc') || codec.startsWith('h264')) &&
        (maxHeight == null || (h is num && h <= maxHeight));
  });

  Set<String> _keys(String key) => switch (raw[key]) {
    final Map m => {for (final k in m.keys) '$k'},
    _ => <String>{},
  };

  /// Subtitle languages written by people, live chat left out.
  Set<String> get subtitles => _keys('subtitles')..remove('live_chat');

  /// Subtitle languages generated by the site.
  Set<String> get automaticCaptions => _keys('automatic_captions');

  /// A flat playlist's items; empty for a single video.
  List<PlaylistEntry> get entries => [
    if (raw['entries'] case final List list)
      for (final e in list)
        if (e is Map<String, Object?>)
          if ((e['id'], e['url'] ?? e['webpage_url']) case (
            final String id,
            final String url,
          ))
            PlaylistEntry(
              id: id,
              url: url,
              title: e['title'] is String ? e['title'] as String : null,
              duration: e['duration'] is num
                  ? Duration(seconds: (e['duration'] as num).round())
                  : null,
            ),
  ];
}
